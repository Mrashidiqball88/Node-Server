// ── Slow-network tests ────────────────────────────────────────────────────────

test.describe('Upload progress UI — progress bar advances and overlay hides correctly', () => {
  /**
   * Verifies the client-side progress bar DOM behaviour when upload.progress
   * events fire mid-flight.
   *
   * Background: CDP Network.emulateNetworkConditions throttles at the real
   * socket layer, but Playwright's page.route() intercepts requests before they
   * reach the network socket — so xhr.upload.progress never fires naturally for
   * mocked routes.  To exercise the UI handler in isolation we monkey-patch
   * XMLHttpRequest.prototype.send to dispatch five synthetic ProgressEvents
   * (20 %, 40 %, 60 %, 80 %, 95 % of the real body size) spread over 1.5 s.
   * The route mock holds for 4 s, so these events land before xhr.onload fires.
   *
   * This test covers client UI behaviour only.  For server-side slow-upload
   * reliability see the "Slow-socket upload" suite below.
   */
  test(
    'synthetic upload events advance the progress bar from 0 % to 100 %',
    async ({ page }) => {
      test.setTimeout(60_000);

      // ── 1. Inject the XHR shim BEFORE page load ───────────────────────
      // addInitScript() runs the function in the page context on every
      // navigation, before any page scripts execute.
      await page.addInitScript(() => {
        const _realSend = XMLHttpRequest.prototype.send;
        XMLHttpRequest.prototype.send = function (body) {
          const upload = this.upload;
          // Measure the serialised body so progress ratios are realistic.
          const total = body ? new Blob([body]).size : 1;
          // Fire 5 synthetic progress events spread across 1.5 s.
          [0.2, 0.4, 0.6, 0.8, 0.95].forEach((ratio, i) => {
            setTimeout(() => {
              upload.dispatchEvent(
                new ProgressEvent('progress', {
                  bubbles: false,
                  lengthComputable: true,
                  loaded: Math.floor(ratio * total),
                  total,
                })
              );
            }, (i + 1) * 300); // 300 ms, 600 ms, 900 ms, 1 200 ms, 1 500 ms
          });
          _realSend.call(this, body);
        };
      });

      // ── 2. Register stub routes; hold the register response for 4 s ───
      await setupRoutes(page, 4_000);
      await page.goto('/driver');

      await fillStep1(page, { phone: '+923001234996' });
      await uploadPhotos(page);
      await page.locator('#reg-submit-btn').click();

      // ── Assert 1: upload-progress overlay appears ─────────────────────
      const overlay = page.locator('#upload-progress-screen');
      await expect(overlay).toBeVisible({ timeout: 10_000 });

      // ── Assert 2: progress bar advances past 0 % BEFORE upload ends ───
      // The first synthetic event fires at ~300 ms after send(); the route
      // mock holds the response for 4 s, so there is a clear window where
      // pct is in the range (0, 100).
      await page.waitForFunction(
        () => {
          const el = document.querySelector('#upload-progress-pct');
          if (!el) return false;
          const pct = parseInt(el.textContent, 10);
          return !isNaN(pct) && pct > 0 && pct < 100;
        },
        { timeout: 15_000 }
      );

      // Snapshot the mid-flight value — it must be strictly positive.
      const midPct = await page.locator('#upload-progress-pct').evaluate(
        (el) => parseInt(el.textContent, 10)
      );
      expect(midPct).toBeGreaterThan(0);

      // ── Assert 3: progress bar reaches 100 % once the response lands ──
      await expect(page.locator('#upload-progress-pct')).toHaveText('100%', {
        timeout: 15_000,
      });
      expect(
        await page.locator('#upload-progress-bar').evaluate(
          (el) => el.style.width
        )
      ).toBe('100%');

      // ── Assert 4: overlay hides after the 600 ms post-success delay ───
      await expect(overlay).toBeHidden({ timeout: 5_000 });

      // ── Assert 5: driver app is the active screen ─────────────────────
      await expect(page.locator('#auth-screen')).toBeHidden({ timeout: 5_000 });
      await expect(page.locator('#app')).toBeVisible({ timeout: 5_000 });

      // ── Assert 6: pending-approval card is rendered in the DOM ────────
      const pendingCardDisplay = await page.locator('#pending-card').evaluate(
        (el) => window.getComputedStyle(el).display
      );
      expect(pendingCardDisplay).not.toBe('none');
    }
  );
});

