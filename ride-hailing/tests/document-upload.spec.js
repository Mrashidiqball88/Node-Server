// ── Real-server slow-upload test ──────────────────────────────────────────────

test.describe('Slow-socket upload — live server accepts slow continuous body within configured timeout', () => {
  /**
   * Context
   * -------
   * server.requestTimeout controls how long the http.Server allows for a
   * request to be received.  The default (Node 18+: 300 000 ms) is sufficient
   * for slow mobile uploads but is left implicit and can be overridden
   * accidentally by a framework upgrade or misconfiguration to a value too
   * short for 2G/3G uploads.
   *
   * The server now sets server.requestTimeout explicitly to 600 000 ms and
   * exposes it via REQUEST_TIMEOUT_MS.  playwright.config.js sets
   * REQUEST_TIMEOUT_MS=8 000 ms so tests use an 8 s budget.
   *
   * What this test proves
   * ---------------------
   * A ~100 KB body streamed in 4 KB chunks with 160 ms gaps takes roughly
   * 4 s — a duration that would be rejected by any timeout set below ~4 s
   * (the "formerly too-short" threshold).  The test sends this body to the
   * real /api/auth/register endpoint and asserts any HTTP response arrives,
   * confirming the server held the TCP connection open and received the
   * complete body within the 8 s configured budget.
   *
   * A socket error (ECONNRESET / ETIMEDOUT) or zero-byte body would mean the
   * server dropped the slow upload — the test would throw/fail.
   */

  test(
    'slow ~4 s upload of ~100 KB body succeeds — server holds connection open within the configured 8 s budget',
    async () => {
      test.setTimeout(25_000);

      // 25 chunks × 160 ms ≈ 4 000 ms  — crosses a sub-4 s "formerly too-short"
      // threshold but stays within the configured 8 000 ms test-mode budget.
      const { status, bodyBytesReceived } = await sendSlowChunked(
        3000,
        '/api/auth/register',
        SLOW_UPLOAD_BODY,
        { chunkSize: 4_096, delayMs: 160 }
      );

      // The server must have received the full body before replying.
      expect(bodyBytesReceived).toBe(Buffer.byteLength(SLOW_UPLOAD_BODY));

      // Any HTTP status proves the server kept the connection alive.
      // 201 = registration success, 409 = duplicate phone, 500 = DB unavailable.
      expect([201, 409, 500]).toContain(status);
    }
  );
});

