// ── Slow-chunked HTTP helper ───────────────────────────────────────────────────
/**
 * Sends `bodyStr` as an HTTP POST to localhost:port/path using real TCP chunks
 * so the server's body-parser must consume them over time — faithfully simulating
 * a driver on a slow mobile connection.
 *
 * Each `chunkSize`-byte slice is written after `delayMs` ms, then we wait for
 * the full HTTP response and return { status, body }.
 *
 * Any HTTP status (201 created, 409 duplicate, 500 DB unavailable) means the
 * server kept the connection alive and received the complete body without timing
 * out.  A connection error or socket reset would throw, failing the test.
 *
 * @param {number} port
 * @param {string} urlPath
 * @param {string} bodyStr
 * @param {{ chunkSize?: number, delayMs?: number }} [opts]
 * @returns {Promise<{ status: number, body: string, bodyBytesReceived: number }>}
 */
function sendSlowChunked(port, urlPath, bodyStr, { chunkSize = 4096, delayMs = 50 } = {}) {
  return new Promise((resolve, reject) => {
    const buf = Buffer.from(bodyStr, 'utf8');
    let settled = false;

    const req = http.request(
      {
        host: '127.0.0.1',
        port,
        path: urlPath,
        method: 'POST',
        headers: {
          'Content-Type':   'application/json',
          'Content-Length': buf.length,
        },
      },
      (res) => {
        let raw = '';
        res.on('data', (d) => (raw += d));
        res.on('end', () => {
          if (settled) return;
          settled = true;
          resolve({ status: res.statusCode, body: raw, bodyBytesReceived: buf.length });
        });
      }
    );

    // When the server enforces requestTimeout it sends 408 and destroys the
    // socket mid-transfer.  Subsequent write() calls produce an ECONNRESET.
    // We ignore those errors if the response was already captured above.
    req.on('error', (err) => {
      if (!settled) { settled = true; reject(err); }
    });

    // Stream body in chunks with artificial delays between each write.
    let offset = 0;
    const tick = () => {
      if (settled) return;   // response already received — stop sending
      if (offset >= buf.length) { req.end(); return; }
      req.write(buf.slice(offset, Math.min(offset + chunkSize, buf.length)));
      offset += chunkSize;
      setTimeout(tick, delayMs);
    };
    tick();
  });
}

